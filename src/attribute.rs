//! Decide which package owns a file, using metadata collected during the scan.

use serde::Serialize;
use std::collections::HashMap;

use crate::feed::BinaryName;

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Owner {
    pub ecosystem: String,
    pub name: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub version: Option<String>,
    /// The metadata file or path rule that identified the owner.
    pub evidence: String,
}

type Store = HashMap<String, Vec<u8>>;

fn text(store: &Store, key: &str) -> Option<String> {
    store.get(key).map(|b| String::from_utf8_lossy(b).into_owned())
}

fn owner(eco: &str, name: &str, version: Option<String>, evidence: impl Into<String>) -> Option<Owner> {
    Some(Owner {
        ecosystem: eco.to_string(),
        name: name.to_string(),
        version,
        evidence: evidence.into(),
    })
}

/// `name-1.2.3` → (`name`, `1.2.3`), splitting at the last `-` followed by a digit.
fn split_name_version(s: &str) -> Option<(&str, &str)> {
    let idx = s
        .char_indices()
        .filter(|&(i, c)| c == '-' && s[i + 1..].starts_with(|d: char| d.is_ascii_digit()))
        .map(|(i, _)| i)
        .next_back()?;
    Some((&s[..idx], &s[idx + 1..]))
}

fn python(path: &str, store: &Store) -> Option<Owner> {
    for (key, data) in store.iter().filter(|(k, _)| k.ends_with(".dist-info/RECORD")) {
        let dist_dir = &key[..key.len() - "/RECORD".len()];
        let Some((site, dist)) = dist_dir.rsplit_once('/') else {
            continue;
        };
        let Some(rel) = path.strip_prefix(site).and_then(|r| r.strip_prefix('/')) else {
            continue;
        };
        let listed = String::from_utf8_lossy(data)
            .lines()
            .any(|l| l.split(',').next() == Some(rel));
        if listed {
            let stem = dist.trim_end_matches(".dist-info");
            let (name, version) = stem.split_once('-').unwrap_or((stem, ""));
            return owner("pypi", &name.replace('_', "-"), Some(version.to_string()), key.clone());
        }
    }
    None
}

fn npm(path: &str, store: &Store) -> Option<Owner> {
    let (prefix, rest) = path.rsplit_once("node_modules/")?;
    let mut parts = rest.split('/');
    let first = parts.next()?;
    let name = if first.starts_with('@') {
        format!("{first}/{}", parts.next()?)
    } else {
        first.to_string()
    };
    let manifest = format!("{prefix}node_modules/{name}/package.json");
    let version = text(store, &manifest)
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
        .and_then(|v| v.get("version")?.as_str().map(str::to_string));
    owner("npm", &name, version, manifest)
}

fn maven(path: &str, store: &Store) -> Option<Owner> {
    let idx = path.rfind(".jar!/")?;
    let jar = &path[..idx + ".jar".len()];
    let prefix = format!("{jar}!/META-INF/maven/");
    for (key, data) in store.iter().filter(|(k, _)| k.starts_with(&prefix) && k.ends_with("/pom.properties")) {
        let props: HashMap<&str, &str> = std::str::from_utf8(data)
            .ok()?
            .lines()
            .filter_map(|l| l.split_once('='))
            .map(|(k, v)| (k.trim(), v.trim()))
            .collect();
        if let (Some(g), Some(a)) = (props.get("groupId"), props.get("artifactId")) {
            return owner("maven", &format!("{g}:{a}"), props.get("version").map(|v| v.to_string()), key.clone());
        }
    }
    let file = jar.rsplit('/').next().unwrap_or(jar).trim_end_matches(".jar");
    let (name, version) = split_name_version(file).unwrap_or((file, ""));
    owner("maven", name, (!version.is_empty()).then(|| version.to_string()), "jar file name")
}

fn jdk(path: &str, store: &Store) -> Option<Owner> {
    let home = path.strip_suffix("/lib/security/cacerts")?;
    let release = format!("{home}/release");
    let version = text(store, &release).and_then(|t| {
        t.lines()
            .find_map(|l| l.strip_prefix("JAVA_VERSION="))
            .map(|v| v.trim_matches('"').to_string())
    });
    owner("java", "jdk", version, if store.contains_key(&release) { release } else { "lib/security/cacerts path".into() })
}

/// Files generated by maintainer scripts, so absent from every package file list.
const GENERATED: [(&str, &str); 3] = [
    ("/etc/ssl/certs/ca-certificates.crt", "ca-certificates"),
    ("/etc/ssl/certs/java/cacerts", "ca-certificates-java"),
    ("/etc/pki/tls/certs/ca-bundle.crt", "ca-certificates"),
];

fn stanzas(t: &str) -> impl Iterator<Item = &str> {
    t.split("\n\n").filter(|s| !s.trim().is_empty())
}

fn dpkg(path: &str, store: &Store) -> Option<Owner> {
    let status_key = store.keys().find(|k| k.ends_with("/var/lib/dpkg/status"))?.clone();
    let root = status_key.trim_end_matches("/var/lib/dpkg/status");
    let local = path.strip_prefix(root)?;
    let info = format!("{root}/var/lib/dpkg/info/");
    let pkg = store
        .iter()
        .filter(|(k, _)| k.starts_with(&info) && k.ends_with(".list"))
        .find(|(_, v)| String::from_utf8_lossy(v).lines().any(|l| l == local))
        .map(|(k, _)| {
            let file = k.rsplit('/').next().unwrap_or(k).trim_end_matches(".list");
            (file.split(':').next().unwrap_or(file).to_string(), k.clone())
        })
        .or_else(|| {
            GENERATED
                .iter()
                .find(|(p, _)| *p == local)
                .map(|(_, n)| (n.to_string(), format!("{local} is generated by {n}")))
        })?;
    let status = text(store, &status_key)?;
    let version = stanzas(&status)
        .find(|s| s.lines().any(|l| l == format!("Package: {}", pkg.0)))
        .and_then(|s| s.lines().find_map(|l| l.strip_prefix("Version: ")))
        .map(str::to_string);
    owner("deb", &pkg.0, version, pkg.1)
}

fn apk(path: &str, store: &Store) -> Option<Owner> {
    let db_key = store.keys().find(|k| k.ends_with("/lib/apk/db/installed"))?.clone();
    let root = db_key.trim_end_matches("/lib/apk/db/installed");
    let local = path.strip_prefix(root)?.trim_start_matches('/');
    let db = text(store, &db_key)?;
    let find = |want: &str| {
        stanzas(&db).find_map(|s| {
            let (mut p, mut v, mut dir) = (None, None, "");
            let mut owns = false;
            for l in s.lines() {
                match l.split_at_checked(2) {
                    Some(("P:", x)) => p = Some(x),
                    Some(("V:", x)) => v = Some(x),
                    Some(("F:", x)) => dir = x,
                    Some(("R:", x)) if format!("{dir}/{x}") == want => owns = true,
                    _ => {}
                }
            }
            owns.then(|| (p.unwrap_or("?").to_string(), v.map(str::to_string)))
        })
    };
    if let Some((p, v)) = find(local) {
        return owner("apk", &p, v, db_key);
    }
    let (_, name) = GENERATED.iter().find(|(p, _)| p.trim_start_matches('/') == local)?;
    let version = stanzas(&db)
        .find(|s| s.lines().any(|l| l == format!("P:{name}")))
        .and_then(|s| s.lines().find_map(|l| l.strip_prefix("V:")))
        .map(str::to_string);
    owner("apk", name, version, format!("/{local} is generated by {name}"))
}

fn path_rules(path: &str) -> Option<Owner> {
    if let Some((_, rest)) = path.split_once("/Cellar/") {
        let mut it = rest.split('/');
        let (name, version) = (it.next()?, it.next()?);
        return owner("brew", name, Some(version.to_string()), "Homebrew Cellar path");
    }
    if let Some((_, rest)) = path.split_once("/registry/src/") {
        let krate = rest.split('/').nth(1)?;
        let (name, version) = split_name_version(krate)?;
        return owner("cargo", name, Some(version.to_string()), "cargo registry path");
    }
    None
}

fn binary(path: &str, binaries: &[BinaryName]) -> Option<Owner> {
    let file = path.rsplit(['/', '!']).next()?;
    let b = binaries.iter().find(|b| b.file == file)?;
    owner(&b.ecosystem, &b.name, None, format!("executable named {file}"))
}

pub fn attribute(path: &str, store: &Store, binaries: &[BinaryName]) -> Option<Owner> {
    python(path, store)
        .or_else(|| path.contains("node_modules/").then(|| npm(path, store)).flatten())
        .or_else(|| maven(path, store))
        .or_else(|| jdk(path, store))
        .or_else(|| dpkg(path, store))
        .or_else(|| apk(path, store))
        .or_else(|| path_rules(path))
        .or_else(|| binary(path, binaries))
}
